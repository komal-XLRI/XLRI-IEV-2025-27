import { existsSync } from "node:fs";
import { resolve } from "node:path";
import nodemailer from "nodemailer";
import { BRAND } from "@/lib/brand";

export const smtpConfigured = Boolean(
  process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASSWORD,
);

let transporter: nodemailer.Transporter | null = null;

function getTransporter() {
  if (!smtpConfigured) return null;
  if (!transporter) {
    const port = Number(process.env.SMTP_PORT ?? 587);
    transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port,
      secure: port === 465,
      auth: { user: process.env.SMTP_USER!, pass: process.env.SMTP_PASSWORD! },
    });
  }
  return transporter;
}

export type SendResult = { delivered: boolean; error?: string };

/**
 * Never throws. A mail provider failing is an operational problem, not a
 * request-shaped one — the caller decides what to tell the user, and the code
 * is always written to the console so an operator is never locked out.
 */
export async function sendOtpEmail(to: string, code: string, name?: string): Promise<SendResult> {
  const logCode = () =>
    console.info(`\n  [IEV] Login code for ${to}: ${code}  (valid 10 minutes)\n`);

  const tx = getTransporter();
  if (!tx) {
    // No SMTP configured — the console is the delivery channel.
    logCode();
    return { delivered: false };
  }

  const from = process.env.SMTP_FROM?.trim();
  if (!from) {
    logCode();
    return {
      delivered: false,
      error:
        "SMTP is configured but SMTP_FROM is not set. Most providers reject mail from an unverified sender. Set SMTP_FROM to an address on a domain verified with your mail provider.",
    };
  }

  try {
    await tx.sendMail({ from, to, ...buildOtpMessage(code, name) });
    return { delivered: true };
  } catch (err) {
    console.error("[mailer] Could not send sign-in code:", err);
    logCode();
    return { delivered: false, error: describeSmtpError(err, from) };
  }
}

/** Turns an SMTP failure into something an administrator can act on. */
function describeSmtpError(err: unknown, from: string): string {
  const code = (err as { responseCode?: number })?.responseCode;
  const raw = err instanceof Error ? err.message : String(err);

  if (code === 553 || code === 550 || /not allowed to relay|sender.*not/i.test(raw)) {
    return `The mail provider refused "${from}" as a sender. The From address must be on a domain verified with your provider — update SMTP_FROM.`;
  }
  if (code === 535 || /auth|credential/i.test(raw)) {
    return "The mail provider rejected the SMTP credentials. Check SMTP_USER and SMTP_PASSWORD.";
  }
  if (/ENOTFOUND|ECONNREFUSED|ETIMEDOUT/i.test(raw)) {
    return "Could not reach the mail server. Check SMTP_HOST, SMTP_PORT and the server's network access.";
  }
  return `The mail provider rejected the message: ${raw}`;
}

const LOGO_CID = "xlri-logo";

/**
 * The email logo is embedded in the message rather than linked.
 *
 * A linked image needs a public URL the portal may not have, and most clients
 * block remote images by default — so the logo would be a grey box on first
 * open, which is exactly when trust matters. Attaching it inline sidesteps
 * both. Generated by `npm run email:logo`; if it is missing the email simply
 * falls back to the text header rather than showing a broken image.
 */
function logoAttachment() {
  const path = resolve(process.cwd(), "public/xlri-logo-email.png");
  if (!existsSync(path)) return null;
  return {
    filename: "xlri-logo.png",
    path,
    cid: LOGO_CID,
    contentDisposition: "inline" as const,
  };
}

/** Builds the full message body. Exported so it can be inspected in tests. */
export function buildOtpMessage(code: string, name?: string) {
  const logo = logoAttachment();
  return {
    subject: `${code} is your ${BRAND.unitShort} Portal sign-in code`,
    text: [
      `${BRAND.institutionFull}, ${BRAND.campus}`,
      `${BRAND.unit}`,
      ``,
      `Your sign-in code is ${code}`,
      `It expires in 10 minutes and can be used once.`,
      ``,
      `If you did not request this code, you can ignore this email.`,
    ].join("\n"),
    html: otpEmailHtml(code, name, Boolean(logo)),
    ...(logo ? { attachments: [logo] } : {}),
  };
}

